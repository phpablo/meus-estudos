L = [4, 10, 2, 8, 16, 25]

menor_valor = min(L)

maior_valor = max(L)

produto = menor_valor * maior_valor

media_geometrica = produto ** 0.5

print(f"A lista L é: {L}")
print(f"O menor elemento da lista é: {menor_valor}")
print(f"O maior elemento da lista é: {maior_valor}")
print(f"A média geométrica entre {menor_valor} e {maior_valor} é: {media_geometrica}")




